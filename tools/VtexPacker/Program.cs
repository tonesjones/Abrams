foreach (var (gamePath, fileName) in files)
{
    var local = Path.Combine(texturesDir, fileName);
    if (!File.Exists(local))
    {
        Console.WriteLine($"SKIP missing: {local}");
        continue;
    }

    var pngBytes = File.ReadAllBytes(local);
    var (width, height) = ReadPngSize(pngBytes);
    Console.WriteLine($"Add {gamePath} ({width}x{height}, {pngBytes.Length} bytes png)");

    var vtex = new VtexWriter
    {
        Width = (ushort)width,
        Height = (ushort)height,
        Reflectivity = new Vector3(1f, 1f, 1f),
        ImageData = pngBytes,
    };

    using var ms = new MemoryStream();
    vtex.Write(ms);
    package.AddFile(gamePath, ms.ToArray());
}

// Optional extra compiled files: pairs of gamePath=localPath after the two required args
for (int i = 2; i + 1 < args.Length; i += 2)
{
    var gamePath = args[i].Replace('\\', '/').TrimStart('/');
    var local = Path.GetFullPath(args[i + 1]);
    if (!File.Exists(local))
    {
        Console.WriteLine($"SKIP extra missing: {local}");
        continue;
    }
    Console.WriteLine($"Add raw {gamePath} ({new FileInfo(local).Length} bytes)");
    package.AddFile(gamePath, File.ReadAllBytes(local));
}

Directory.CreateDirectory(Path.GetDirectoryName(outputVpk)!);
package.Write(outputVpk);
Console.WriteLine($"Wrote {outputVpk} ({new FileInfo(outputVpk).Length} bytes)");
return 0;

static (int width, int height) ReadPngSize(byte[] png)
{
    // PNG IHDR: 8 sig + 4 len + 4 'IHDR' + 4 width + 4 height
    if (png.Length < 24)
        throw new InvalidDataException("PNG too small");
    int width = (png[16] << 24) | (png[17] << 16) | (png[18] << 8) | png[19];
    int height = (png[20] << 24) | (png[21] << 16) | (png[22] << 8) | png[23];
    return (width, height);
}

