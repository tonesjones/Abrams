    public void Write(Stream output)
    {
        output.Write(Preamble);
        using var writer = new BinaryWriter(output, System.Text.Encoding.UTF8, leaveOpen: true);

        writer.Write((ushort)1); // version
        writer.Write((ushort)0); // flags
        writer.Write(Reflectivity.X);
        writer.Write(Reflectivity.Y);
        writer.Write(Reflectivity.Z);
        writer.Write(0.0f); // A
        writer.Write(Width);
        writer.Write(Height);
        writer.Write((ushort)1); // depth
        writer.Write((byte)16); // PNG_RGBA8888
        writer.Write((byte)1); // mips
        writer.Write((uint)0); // Picmip0Res
        writer.Write((uint)8); // ExtraData offset
        writer.Write((uint)1); // ExtraData count
        writer.Write((uint)0xFFFF);
        writer.Write((uint)8);
        writer.Write((uint)1024);
        writer.Write(new byte[1024]);
        writer.Write(ImageData);
    }
